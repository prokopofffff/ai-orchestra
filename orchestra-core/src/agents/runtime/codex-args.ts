import fs from "node:fs";
import path from "node:path";
import type { AgentRunInput } from "./types";

/**
 * CLI argv + `config.toml` content for one Codex run. Caller writes the TOML
 * to `<CODEX_HOME>/config.toml` before spawning so the CLI picks up MCP wiring.
 *
 * Three Codex-specific notes:
 *   - No `--max-budget-usd` on Codex (Claude has one); runtime enforces the
 *     cap by watching token usage events and SIGTERMing on threshold.
 *   - `--sandbox workspace-write` enables OS-level filesystem confinement
 *     (Seatbelt on macOS, Landlock/seccomp on Linux). Closes the read-side
 *     path-escape gap.
 *   - `--ephemeral` keeps the per-spawn `$CODEX_HOME/sessions` dir from
 *     accumulating run files we never replay.
 */
export function buildCodexCliArgs(input: {
  cwd: string;
  model: string;
  resumeSessionId?: string;
}): string[] {
  // ChatGPT-subscription accounts reject every named model server-side
  // (gpt-5, gpt-5-codex, gpt-4o, o3, …). The CLI only accepts the
  // account-default in that case — selected by OMITTING --model. The
  // resolver sets model to this sentinel when codex auth_mode === "chatgpt".
  const modelFlag = input.model && input.model !== "chatgpt-default"
    ? ["--model", input.model]
    : [];

  if (input.resumeSessionId) {
    // Codex resume is a separate subcommand, not a flag. Spawner calls this
    // path only when resumeSessionId is set; the parser handles the same
    // event stream either way.
    return [
      "exec", "resume", input.resumeSessionId,
      "--json", "--sandbox", "workspace-write", "--skip-git-repo-check",
      "--cd", input.cwd,
      ...modelFlag,
    ];
  }
  return [
    "exec",
    "--json",
    "--sandbox", "workspace-write",
    // Codex refuses non-interactively when cwd isn't a git repo or one of
    // the user's configured trusted dirs ("Not inside a trusted directory
    // and --skip-git-repo-check was not specified"). Worktrees ARE git
    // repos so this is a no-op there; for TL chat in a fresh /workspace/*
    // dir it's the difference between a real run and an immediate exit.
    // Actual write isolation still comes from --sandbox workspace-write.
    "--skip-git-repo-check",
    "--cd", input.cwd,
    ...modelFlag,
    "--ephemeral",
  ];
}

/**
 * Generate `config.toml` content from our normalized MCP servers map. Codex
 * reads MCP wiring from `$CODEX_HOME/config.toml` (not a flag) so we write
 * it before each spawn.
 *
 * TOML serialization is bespoke and minimal — we only emit `[mcp_servers.<id>]`
 * tables with command/args/env. JSON.stringify produces valid TOML basic
 * strings for all UTF-8 content, so no quoting bugs even with shell-special
 * chars in env values.
 */
export function buildCodexConfigToml(mcpServers: AgentRunInput["mcpServers"]): string {
  const parts: string[] = [
    "# Generated by orchestra per-spawn. Do not edit by hand — overwritten on next run.",
    "",
  ];
  for (const [name, cfg] of Object.entries(mcpServers)) {
    if (!isValidTomlBareKey(name)) {
      // Skip silently rather than throw — a misnamed server would fail at
      // codex parse time and the run would error out anyway. Log via the
      // runtime when this branch fires.
      continue;
    }
    parts.push(`[mcp_servers.${name}]`);
    parts.push(`command = ${tomlString(cfg.command)}`);
    parts.push(`args = ${tomlStringArray(cfg.args)}`);
    if (cfg.env && Object.keys(cfg.env).length > 0) {
      parts.push(`env = ${tomlInlineTable(cfg.env)}`);
    }
    parts.push("");
  }
  return parts.join("\n");
}

/**
 * Write the per-spawn config.toml. Caller passes the CODEX_HOME for this
 * project; the file is overwritten on every spawn so stale MCP entries
 * never leak into a later run.
 */
export function writeCodexConfigToml(
  codexHome: string,
  mcpServers: AgentRunInput["mcpServers"],
): void {
  fs.mkdirSync(codexHome, { recursive: true });
  fs.writeFileSync(
    path.join(codexHome, "config.toml"),
    buildCodexConfigToml(mcpServers),
    { mode: 0o600 },
  );
}

// ─── TOML serialization helpers ───────────────────────────────────────────

function tomlString(s: string): string {
  // JSON's string encoding is a valid TOML basic string for any UTF-8 input.
  // Same escaping rules: `\\`, `\"`, `\n`, `\t`, `\u00XX`.
  return JSON.stringify(s);
}

function tomlStringArray(arr: string[]): string {
  return "[" + arr.map(tomlString).join(", ") + "]";
}

function tomlInlineTable(obj: Record<string, string>): string {
  const entries = Object.entries(obj).map(
    ([k, v]) => `${isValidTomlBareKey(k) ? k : tomlString(k)} = ${tomlString(v)}`,
  );
  return "{ " + entries.join(", ") + " }";
}

/**
 * TOML bare keys allow [A-Za-z0-9_-]. Anything else needs quoting. We use
 * this to decide whether to wrap an MCP server name in quotes; ours are
 * generated with safe characters (e.g. "orchestra-signal-tool") so this
 * almost always returns true.
 */
function isValidTomlBareKey(s: string): boolean {
  return /^[A-Za-z0-9_-]+$/.test(s);
}
